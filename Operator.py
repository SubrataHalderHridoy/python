# Less than or equal to  
print ("a <= b:", a <= b) # True 


#Assignment operator  
x = 10  
print("x =", x) # 10  
x += 5 # equivalent to x = x + 5  
print("x += 5 ->", x) # 15  
x -= 3 # equivalent to x = x - 3 
print("x -= 3 ->", x) # 12  
x *= 2 # equivalent to x = x * 2  
print("x *= 2 ->", x) # 24  
x /= 4 # equivalent to x = x / 4  
print("x /= 4 ->", x) # 6.0  
x %= 4 # equivalent to x = x % 4  
print("x %= 4 ->", x) # 2.0  
x **= 3 # equivalent to x = x ** 3  
print("x **= 3 ->", x) # 8.0 
